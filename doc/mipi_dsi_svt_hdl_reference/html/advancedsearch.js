  document.write("  <td><input NAME=\"searchbtn\" TYPE=button VALUE=\" Search \" onChange=\"SearchFunction(form.searchtext.value, '', form.searchmode.value)\"></td>\n");
  document.write("  <td><input NAME=\"searchtext\" TYPE=text VALUE=" + searchstring + " onChange=\"SearchFunction(form.searchtext.value, '', form.searchmode.value)\"></td>\n");
  document.write("  <td><select NAME=\"searchmode\" SIZE=1 >");
  if (compare_type == "simple") {
    document.write("      <option value=simple>simple</option>");
    document.write("      <option value=regexpr>reg expr</option>");
  }
  else {
    document.write("      <option value=regexpr>reg expr</option>");
    document.write("      <option value=simple>simple</option>");
  }
  document.write("  </select></td>");
  document.write("</tr></table></form></li>\n");
  document.write("</ul>\n");
  document.write("</div>\n");

  document.write( "<h1>Search results for '" + teststring + "'</h1>\n" );
  if (compare_type == "simple") {
    document.write( "<hr>\n");
    document.write( "<blockquote>\n");
    document.write( "<h2>Exact matches</h2>\n");
    document.write( "  <table class=\"SearchResults\">\n");

    numHits = 0;
    for (k=0; k<3336; k=k+1) {
      if (TestExact( teststring, nm[k] )) {
        WriteSymbolEntry( teststring, nm[k] )
        numHits = numHits + 1;
    }
    }
    if (numHits == 0) {
      document.write( "<tr><td class=\"SearchResults\">No exact matches ...</td></tr>\n");
    }
    document.write( "  </table>\n" );
    document.write( "</blockquote>\n");

    document.write( "<hr>\n");
    document.write( "<blockquote>\n");
    document.write( "<h2>Partial matches</h2>\n");
    document.write( "  <table class=\"SearchResults\"> \n");

    numHits = 0;
    for (k=0; k<3336; k=k+1) {
      rc = TestPartial( teststring, nm[k] );
      if (rc == 1) { // found partial match
        WriteSymbolEntry( teststring, nm[k] );
        numHits = numHits + 1;
      }
    }
    if (numHits == 0) {
      document.write( "<tr><td class=\"SearchResults\">No partial matches ...</td></tr>\n");
    }
    document.write( "  </table>\n");
    document.write( "</blockquote>\n");
  }

  else {  // if it's not a simple search do a regular expression search
    var searchregexpr = new RegExp(searchstring);  // build a regular expression obj
    var name;

    document.write( "<hr>\n");
    document.write( "<blockquote>\n");
    document.write( "<h2>Matches</h2>\n");
    document.write( "  <table class=\"SearchResults\"> \n");

    numHits = 0;
    for (k=0; k<3336; k=k+1) {
      pos = nm[k].search(" ");
      name = nm[k].substr( pos+1 );

      if (searchregexpr.test(name)) {  // test name against reg expr
        WriteSymbolEntry( "", nm[k] );
        numHits = numHits + 1;
      }
    }
    if (numHits == 0) {
      document.write( "<tr><td class=\"SearchResults\">No matches ...</td></tr>\n");
    }
    document.write( "  </table>\n");
    document.write( "</blockquote>\n");
  }

  document.write( "<hr>\n");
  document.write( "</body></html>\n");
  document.close();
